export type { TKey };

export function useTranslation() {
  const l1 = (getString(KEYS.SELECTED_L1) ?? "en") as string;
  const dict = ALL[l1 as keyof typeof ALL] ?? en;

  function t(key: TKey, params?: Record<string, string | number>): string {
    let val = dict[key] ?? en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        val = val.replaceAll(`{{${k}}}`, String(v));
      }
    }
    return val;
  }

  return { t, l1 };
}
