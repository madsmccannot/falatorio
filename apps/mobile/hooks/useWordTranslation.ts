export function useWordTranslation() {
  const l1 = getString(KEYS.SELECTED_L1) ?? "en";

  const dict = useMemo(() => DICTIONARIES[l1] ?? DICTIONARIES["en"] ?? {}, [l1]);

  const translate = useCallback(
    (word: string): string | null => {
      const normalized = word.toLowerCase().replace(/[.,!?;:'"()]/g, "");
      return dict[normalized] ?? null;
    },
    [dict],
  );

  return { translate, isLoading: false };
}
